// ピッチ判定「モデル音声基準化」閾値設定 (Priority 2)
//
// deviation(t) = userSemitone(t) - modelSemitone(t) （話者内メディアンF0基準のセミトーン差）
// を使って「モデルからのズレ」だけを癖として扱うための閾値をここに集約する。
// 固定値をロジック内にハードコードせず、本ファイルで一元管理し調整可能にしておく。
//
// 決定根拠 (logs/validation-log.jsonl のピッチ関連 itemFeedback より):
//
// - validation-1783981740093 (2026-07-13):
//   「文中や文尾の上昇下降は、フラットな状態から計算するのではなくしてほしい。疑問文であれば、
//    もともとモデル音声でも、上昇下降が発生するわけなので...モデル音声の音程をプラスマイナス0%
//    として、各部分、音節ごと、で算出する必要がある」
//   → 本モジュール全体（deviation ベース判定）の直接的な設計根拠。
//
// - validation-1783684790045 / 1783727425572 / 1783727681496 (2026-07-10):
//   「Could you help me?」の「もらえますか」の「ら」の音程上昇を3回連続で miss 判定。
//   対象文は依頼の疑問文でモデル音声自体が文末で自然に上昇するため、自己相対(絶対)判定では
//   この自然な上昇を毎回「癖」として誤検出していた。モデル比較後は、モデルとほぼ同じ量の
//   上昇であれば deviation はゼロに近づき natural 判定になるべき。
//   → naturalToleranceSemitone の根拠（モデル自身の発話ゆらぎ・TTSの表現ゆれを吸収する余白）。
//
// - validation-1783861683517 (2026-07-12):
//   自己相対のゾーン分割（3〜5分割の均等時間割り）で「音域差13.5半音」という値が出て、
//   ユーザーが「この分析自体が誤りである可能性の高さを見ています」と指摘。
//   → 均等時間分割ではなく、Azureの単語タイムスタンプで区切ってサンプリングし、
//     話者内メディアンでセミトーン正規化することでノイズを抑える設計にした一因。
//
// - validation-1784016974362 / 1783981375359 (2026-07-13/14):
//   「疑問文であることは加味されているのか。モデル音声をプラスマイナス0%として分析できているか」
//   という趣旨の疑問が繰り返し記録されている。
//   → 本実装のコア動機。今後、実際のモデル×ユーザー音声ペアから deviation の分布を蓄積し、
//     再チューニングする前提。閾値変更時は npm run check / npm run smoke:v012 で
//     既存の正解ケースが壊れていないか必ず確認すること。
//
// 現時点では「話者内メディアン正規化後の deviation そのもの」の実測分布がログに存在しない
// （過去ログは自己相対アルゴリズムの出力しか記録していない）ため、以下は暫定の初期値。
// ユーザーが「合っている/違う」と判定した境界の記述（上記引用）から方向性のみ確定させ、
// 数値は対称的な単純設計から出発し、以後の反復チューニングで精緻化する。

module.exports = {
  version: "pitch-thresholds-v1-2026-07-14",

  // 文末(最終語)の deviation。この範囲内はモデルとほぼ同じ動きとみなし「自然」とする。
  naturalToleranceSemitone: 1.2,

  // naturalToleranceSemitone 〜 strongDeviationSemitone の間は「軽い違和感」帯。
  // trace 扱いとし、分析表示のみで音声には強く反映しない（絶対ルール: trace/low信頼度は表示のみ）。
  strongDeviationSemitone: 2.2,

  // 文中(語間)の deviation 変化量。これ以上の変化を「上げ」「下げ」とみなす。
  // 実機テスト(2026-07-14, "Could you help me?" をモデルに寄せて自然に発話)で、
  // 1.0半音だと単語ごとのピッチ推定ノイズだけで方向転換が2回発生し、zigzag(高)に
  // 誤判定されるケースを確認。1.5半音に引き上げてノイズ耐性を上げた。
  midSentenceMoveSemitone: 1.5,

  // 文中で方向転換がこの回数「かつ」レンジがこれ以上の場合のみジグザグ(1語ずつ区切れる棒読み感)とみなす。
  // (回数だけでの判定はノイズに弱いため、pitchAlignmentService.buildDeviationContour で
  //  方向転換回数とレンジの両方を必須条件にしている。)
  zigzagMinDirectionChanges: 2,
  zigzagRangeSemitone: 3.0,

  // 方向転換1回でもレンジがこれ以上なら「目立つ上げ下げ」(phrase_movement)。
  phraseMovementRangeSemitone: 2.0
};
